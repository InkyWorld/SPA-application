-- ---------------------------------------------------------------------
-- 2. CAPTCHA challenge store (django-simple-captcha).
-- One row per issued challenge; deleted on first verification attempt
-- (one-time use) or swept when expired, so the table never grows forever.
-- ---------------------------------------------------------------------
CREATE TABLE "captcha_captchastore" (
    "id" integer NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "challenge" varchar(32) NOT NULL,
    "response" varchar(32) NOT NULL,
    "hashkey" varchar(40) NOT NULL UNIQUE,
    "expiration" timestamptz NOT NULL
);

-- ---------------------------------------------------------------------
-- 3. Django content types and migrations.
-- These are framework tables used by permissions, admin and migration
-- tracking and are part of the deployed database.
-- ---------------------------------------------------------------------
CREATE TABLE "django_content_type" (
    "id" integer NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "app_label" varchar(100) NOT NULL,
    "model" varchar(100) NOT NULL,
    CONSTRAINT "django_content_type_app_label_model_uniq"
        UNIQUE ("app_label", "model")
);

CREATE TABLE "django_migrations" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "app" varchar(255) NOT NULL,
    "name" varchar(255) NOT NULL,
    "applied" timestamptz NOT NULL
);

-- ---------------------------------------------------------------------
-- 4. Django authentication and authorization.
-- JWT authenticates these users; comments intentionally keep an author
-- snapshot and therefore do not have a foreign key to auth_user.
-- ---------------------------------------------------------------------
CREATE TABLE "auth_group" (
    "id" integer NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "name" varchar(150) NOT NULL UNIQUE
);

CREATE TABLE "auth_permission" (
    "id" integer NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "name" varchar(255) NOT NULL,
    "content_type_id" integer NOT NULL,
    "codename" varchar(100) NOT NULL,
    CONSTRAINT "auth_permission_content_type_codename_uniq"
        UNIQUE ("content_type_id", "codename"),
    CONSTRAINT "auth_permission_content_type_fk"
        FOREIGN KEY ("content_type_id") REFERENCES "django_content_type" ("id")
        DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE "auth_user" (
    "id" integer NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "password" varchar(128) NOT NULL,
    "last_login" timestamptz NULL,
    "is_superuser" boolean NOT NULL,
    "username" varchar(150) NOT NULL UNIQUE,
    "first_name" varchar(150) NOT NULL,
    "last_name" varchar(150) NOT NULL,
    "email" varchar(254) NOT NULL,
    "is_staff" boolean NOT NULL,
    "is_active" boolean NOT NULL,
    "date_joined" timestamptz NOT NULL
);

CREATE TABLE "auth_group_permissions" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "group_id" integer NOT NULL,
    "permission_id" integer NOT NULL,
    CONSTRAINT "auth_group_permissions_uniq" UNIQUE ("group_id", "permission_id"),
    CONSTRAINT "auth_group_permissions_group_fk"
        FOREIGN KEY ("group_id") REFERENCES "auth_group" ("id")
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT "auth_group_permissions_permission_fk"
        FOREIGN KEY ("permission_id") REFERENCES "auth_permission" ("id")
        DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE "auth_user_groups" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "user_id" integer NOT NULL,
    "group_id" integer NOT NULL,
    CONSTRAINT "auth_user_groups_uniq" UNIQUE ("user_id", "group_id"),
    CONSTRAINT "auth_user_groups_user_fk"
        FOREIGN KEY ("user_id") REFERENCES "auth_user" ("id")
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT "auth_user_groups_group_fk"
        FOREIGN KEY ("group_id") REFERENCES "auth_group" ("id")
        DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE "auth_user_user_permissions" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "user_id" integer NOT NULL,
    "permission_id" integer NOT NULL,
    CONSTRAINT "auth_user_user_permissions_uniq" UNIQUE ("user_id", "permission_id"),
    CONSTRAINT "auth_user_user_permissions_user_fk"
        FOREIGN KEY ("user_id") REFERENCES "auth_user" ("id")
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT "auth_user_user_permissions_permission_fk"
        FOREIGN KEY ("permission_id") REFERENCES "auth_permission" ("id")
        DEFERRABLE INITIALLY DEFERRED
);

