-- ---------------------------------------------------------------------
-- 1. Comments tree.
-- Top-level comments are nodes with parent_id IS NULL (MPTT level = 0).
-- Replies nest infinitely via the self-referencing parent FK (MPTT
-- maintains lft/rght/tree_id/level automatically on save).
-- Author snapshot (user_name/email) is copied from the JWT profile at
-- post time, so later profile edits never rewrite history.
-- ---------------------------------------------------------------------
CREATE TABLE "comments_comment" (
    "id" bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    "user_name" varchar(50) NOT NULL,
    "email" varchar(254) NOT NULL,
    "home_page" varchar(500) NOT NULL,
    "text" text NOT NULL,
    "image" varchar(100) NULL,
    "text_file" varchar(100) NULL,
    "created_at" timestamptz NOT NULL,
    "lft" integer NOT NULL CHECK ("lft" >= 0),
    "rght" integer NOT NULL CHECK ("rght" >= 0),
    "tree_id" integer NOT NULL CHECK ("tree_id" >= 0),
    "level" integer NOT NULL CHECK ("level" >= 0),
    "parent_id" bigint NULL
);
